public class Formacao {
    public String nivel;
    public boolean conluido;
    public String instituicao;
    public int ano;

    public Formacao(String nivel, boolean conluido, String instituicao, int ano) {
        this.nivel = nivel;
        this.conluido = conluido;
        this.instituicao = instituicao;
        this.ano = ano;
    }
}
